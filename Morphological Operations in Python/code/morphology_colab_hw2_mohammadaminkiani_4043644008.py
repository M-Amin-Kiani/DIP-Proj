def run_closing_experiment(circles: np.ndarray):
    closed = closing(circles, footprint=disk(10))

    fig, axes = plt.subplots(1, 2, figsize=(10, 5))
    axes[0].imshow(circles, cmap="gray", vmin=0, vmax=1)
