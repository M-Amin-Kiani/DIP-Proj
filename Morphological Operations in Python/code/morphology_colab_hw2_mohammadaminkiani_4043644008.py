    axes[1].imshow(closed, cmap="gray", vmin=0, vmax=1)
    axes[1].set_title("Closed image with disk r=10")
    axes[1].axis("off")
    plt.tight_layout()
    save_fig(fig, "closing_results.png")
    return closed

